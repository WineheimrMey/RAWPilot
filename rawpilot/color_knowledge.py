DIAGNOSIS_KNOWLEDGE = """
采用可执行的摄影后期诊断，不要直接套风格：
- 分别判断中间调、亮端、暗端，不用“整体偏暗/偏亮”代替区域分析。
- 标出人物/主体、天空、背景、灯具/火花、肤色和中性色；说明哪些区域需要相反方向的局部处理。
- 夜景与混合光要区分钨丝灯、黄绿/青绿 LED、环境蓝光和点状高光，不能把所有光源强行中和。
- 识别源片已有的运动模糊、噪声与光晕风险，提醒后续避免用清晰度、去朦胧和锐化将其放大。
- 建议必须依次覆盖：技术基准、区域层次、色彩关系、克制风格、细节保护。
- 同时识别应用场景与交付语境：单张、组照/婚礼活动、参考图匹配、商业色准、网页 SDR、印刷或 HDR。
"""

STYLE_KNOWLEDGE = """
把风格词翻译为可观察的五个维度，而不是套固定预设：
1. 影调基调：高调/平衡/低调、黑位、亮部滚降、对比形状；
2. 色彩关系：中性/冷/暖、主色与点缀色、互补或邻近关系；
3. 饱和分布：全局克制还是选择性色彩突出；
4. 质感：干净、柔和、清晰、颗粒、抛光或粗粝；
5. 空间层级：主体、背景、天空和实用光源谁主谁次。
常用路由：自然纪实；干净商业/编辑；明亮通透；情绪低调；克制电影感；暖金/柔琥珀；
冷蓝/都市编辑；低饱和大地/鼠尾草；奢华时尚；复古哑光/胶片；黑白。
“电影感”不得默认青橙；“高级”应落实为端点受控、饱和克制、肤色/材质可信和边缘干净；
“通透”不是单纯提高曝光与清晰度；“胶片感”必须说明冷暖家族、端点行为和颗粒尺度。
风格强度只缩放曲线、分级、选择性 HSL、颗粒和暗角，不缩放曝光救援、削减溢出、镜头校正、
降噪、肤色与产品色保护。强风格仍必须通过主体可读、肤色/材质可信和无伪影门槛。
"""

SERIES_KNOWLEDGE = """
组照与参考图采用三层模型：
- 每张重算的技术层：配置文件可信度、白平衡、曝光、亮暗端、降噪与锐化；
- 谨慎共享的风格层：曲线形状、冷暖关系、选择性 HSL 倾向、颗粒和暗角哲学；
- 每张适配的局部层：主体/人物/天空/背景蒙版、特殊灯光与局部明暗。
按机位、相机与光线建立分组，每组先选一张 hero frame 通过复审，再传播稳定风格，禁止整套参数盲目同步。
参考图匹配的是影调、色彩、饱和分布、质感与层级，不复制绝对滑杆值。批次复审要检查相邻帧亮度/白平衡跳变、
同一人物肤色连续性、白衣/品牌色/墙面/绿植和实用灯的一致性，并抽查最暗、最亮、最高 ISO 与混合光最重的照片。
商业产品/艺术品优先色准与材质；婚礼保护白衣、黑衣与多样肤色；食物保留食欲暖色但保持餐具中性；
舞台保留有动机的彩光；黑白用原始色彩的明度映射建立分离，不等于简单去饱和。
"""

PLANNING_KNOWLEDGE = """
执行 Lightroom 调色导演工作流：
诊断 → 技术基准 → 区域塑形 → 色彩关系 → 风格 → 细节 → 成片复审。
1. 技术基准：保留可信的 As Shot 白平衡；Exposure 负责中间调，Highlights/Whites 负责亮端，
   Shadows/Blacks 负责暗端。先得到可用动态范围，再增加对比与风格。
2. 区域塑形：两块区域需要相反调整时必须分区。局部问题不能用全局参数补偿。
3. 色彩关系：先白平衡与克制的 Vibrance，再处理确实存在的 HSL 色域。
   红/橙通常包含肤色；单个绿色灯应使用窄色域或局部调整，不得用全局 Tint 制造偏绿。
4. 风格：曲线、色彩分级、颗粒、暗角最后加入。“电影感”是光线层级和冷暖关系，
   不是压黑、青橙和高对比的机械叠加。
5. 细节：先降噪再锐化；夜景、高 ISO、天空和皮肤提高锐化蒙版，限制 Texture/Clarity/Dehaze，
   防止鬼影、光晕、色噪和塑料感。
6. 常规首稿优先范围：Exposure -1..+1 EV；基础色调 ±35；Texture/Clarity/Dehaze ±15；
   Vibrance ±25；Saturation ±12；HSL Hue ±20、Saturation/Luminance ±30；
   色彩分级饱和度 0..18；颗粒 0..25；暗角 0..-18；局部曝光 -1..+1 EV。
   超出常规范围必须有明确诊断/意图支持，并交给成片复审验证。
7. 每个非零参数都应能对应一个画面问题或用户要求；同一目的不要在多个控制上重复叠加。
""" + STYLE_KNOWLEDGE + SERIES_KNOWLEDGE

REVIEW_KNOWLEDGE = """
成片必须通过 BEFORE/AFTER 对照复审：
- 逐条核对用户的显式要求，而不是只判断 AFTER 是否“有风格”。
- 关键门槛：主体可读；没有新增大面积死黑/死白；没有新增全局绿/洋红色偏、荧光绿灯污染、
  青色肤色或失控溢色；没有被调色放大的鬼影、运动拖影、边缘光晕、锐化脆边、塑料感和蒙版边界。
- 区分源片已有缺陷与 AFTER 放大的缺陷。原有模糊不是新增鬼影，但过量 Clarity/Dehaze/锐化
  让它更显眼时属于调色失败。
- 修订使用最少的相关控制，保留已认可区域。暗部失败先判断是中间调、阴影、黑位、曲线还是暗角；
  绿色失败先判断是全局 Tint 还是局部绿/黄/青色域；光晕失败先降低微对比和锐化细节。
- 最多自动返工两次；仍未通过时保留版本并明确报告剩余问题。
- 风格复审逐项判断影调基调、色彩关系、饱和分布、质感与空间层级，不能把“有色偏”当成“有风格”。
- 组照还要与 hero frame 和相邻帧对比；单张好看但造成亮度、白平衡、肤色或品牌色跳变，同样不能通过。
- 网页 SDR 检查实际 sRGB 导出；印刷需软打样；HDR 是独立交付分支，不能把 HDR 式平坦恢复直接套到 SDR JPEG。
""" + STYLE_KNOWLEDGE
